(* --- *)
module Log = Marionnet_log
module UnixExtra = Ocamlbricks.UnixExtra
module FilenameExtra = Ocamlbricks.FilenameExtra
module Gettext_builder = Ocamlbricks.Gettext_builder
(* Generated by dune (i18n/dune, (generate_sites_module)): the relocatable
   directories of the `locale' site where dune installs the .mo catalogues.
   `Sites.locale : string list'. *)
module Sites = Marionnet_sites.Locations.Sites
(* --- *)
let text_domain = "marionnet"
let file_dot_mo = (text_domain ^ ".mo")

(* The cascade below decides which catalogue the whole interface will speak, and
   it decides it at module initialization time — that is, before the log is able
   to print anything: marionnet_log.ml gives the log the constant debug level 0
   until Initialization replaces it. A Log.printf issued here is therefore
   dropped, whatever verbosity the user asked for. Hence this deferred
   diagnosis: the messages are built now, and printed by `log_diagnosis' below,
   which Initialization calls as soon as the level is set. That blindness is what
   let this binary read another Marionnet's catalogue for months, unnoticed
   (episode 15 of the work-stream `marionnet-todo-transverse'). *)
let diagnosis_lines = ref []
let diagnosis_say fmt = Printf.ksprintf (fun s -> diagnosis_lines := s :: !diagnosis_lines) fmt

(** Where the catalogues of THIS repository are, when the binary runs from the
    build tree. In that case dune-site knows nothing: the %%DUNE_PLACEHOLDER%% of
    i18n/Locations.ml is rewritten by `dune install' only, so `Sites.locale' is
    empty (measured 2026-08-21). The catalogues are nevertheless already there,
    in the install directory that `dune build' produces anyway. Recognizing the
    shape <root>/_build/default/bin/<exe> is deliberate and narrow: an installed
    binary never matches it, and nothing else in the code knows about `_build'. *)
let locale_directory_of_the_development_tree () =
  let exe = FilenameExtra.to_absolute (Sys.executable_name) in
  let bin_dir     = Filename.dirname exe in
  let default_dir = Filename.dirname bin_dir in
  let build_dir   = Filename.dirname default_dir in
  if (Filename.basename bin_dir) = "bin"
  && (Filename.basename default_dir) = "default"
  && (Filename.basename build_dir) = "_build"
  then
    Some (FilenameExtra.concat_list [build_dir; "install"; "default"; "share"; text_domain; "locale"])
  else
    None
;;

(** The candidate directories, by decreasing priority, each with the name of the
    way it comes from. The name is not decoration: it is what `log_diagnosis'
    prints, so that a catalogue may be traced back to the decision which chose
    it. MARIONNET_LOCALEPREFIX comes before the development tree because an
    explicit override must win over an inference. *)
let localeprefix_candidates_by_origin =
  [ ("the dune-site `locale' directories", Sites.locale);
    ("MARIONNET_LOCALEPREFIX", Option.to_list (Configuration.get_string_variable "MARIONNET_LOCALEPREFIX"));
    ("the development tree (_build)", Option.to_list (locale_directory_of_the_development_tree ()));
    ("Meta.localeprefix (CONFIGME)", [Meta.localeprefix]);
  ]
;;

(** Look for `marionnet.mo' in the given directories, laid out as <lang>/LC_MESSAGES/.
    ~follow is not cosmetic here: in a directory built by dune each
    <lang>/LC_MESSAGES/marionnet.mo is a symbolic LINK towards the catalogue compiled under
    _build/default/i18n/, and UnixExtra.find stats with lstat when ~follow is absent — a link is then not a
    regular file ('f'), so the whole directory looks empty. Measured 2026-08-21: this
    is precisely what made MARIONNET_LOCALEPREFIX look ineffective. *)
let search_marionnet_dot_mo directories =
  UnixExtra.find_first_and_map ~follow:() ~kind:'f' ~maxdepth:3
    ~basename:file_dot_mo (fun d _ -> d) directories
;;

(** A simple heuristics to infer the location of the `locale' directory in desperate
    situations, when no candidate directory contains a file `marionnet.mo'.
    No ~follow here, on purpose: this walks the whole /usr, where following links means
    walking parts of it several times — and an installed catalogue is a plain file. *)
let try_to_infer_localeprefix_searching_marionnet_dot_mo_in_usr () =
  let (locale_dirs,_) =
    UnixExtra.find ~kind:'d' ~maxdepth:3 ~basename:"locale" ["/usr"]
  in
  UnixExtra.find_first_and_map ~kind:'f' ~maxdepth:3
    ~basename:file_dot_mo (fun d _ -> d) locale_dirs
;;

(** The method deciding the locale prefix: *)
let localeprefix =
  let rec choose = function
    | [] -> None
    | (origin, directories) :: rest ->
        (match search_marionnet_dot_mo directories with
         | Some dir -> Some (origin, dir)
         | None     -> choose rest
         )
  in
  let () =
    List.iter
      (function
       | (origin, [])          -> diagnosis_say "Gettext: no candidate directory from %s" origin
       | (origin, directories) -> diagnosis_say "Gettext: candidate directories from %s: %s" origin (String.concat ", " directories)
       )
      localeprefix_candidates_by_origin
  in
  match choose localeprefix_candidates_by_origin with
  | Some (origin, dir) ->
      diagnosis_say "Gettext: `%s' found in `%s', chosen from %s" file_dot_mo dir origin;
      dir
  | None ->
      (* It's a desperate situation, but we try to find it ourself: *)
      (match try_to_infer_localeprefix_searching_marionnet_dot_mo_in_usr () with
       | Some dir ->
           diagnosis_say "Gettext: WARNING: no candidate directory holds `%s'; falling back on `%s', found by searching /usr" file_dot_mo dir;
           diagnosis_say "Gettext: WARNING: this catalogue belongs to ANOTHER Marionnet (the one installed on this machine): the translations you read are not necessarily those of this binary";
           dir
       | None     ->
           diagnosis_say "Gettext: WARNING: `%s' not found in any candidate directory nor under /usr: the interface stays in English" file_dot_mo;
           (match List.concat_map snd localeprefix_candidates_by_origin with
            | dir :: _ -> dir
            | []       -> Meta.localeprefix (* so much for that... *)
            )
       )
;;

(** Print what the cascade above decided, now that the log is able to print.
    Called by Initialization, as soon as the debug level is set. *)
let log_diagnosis () =
  List.iter (fun line -> Log.printf1 "%s\n" line) (List.rev !diagnosis_lines)
;;

